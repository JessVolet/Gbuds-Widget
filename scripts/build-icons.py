"""Compile the editable, approved SVGs into themeable QML image sources."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
ET.register_namespace("", "http://www.w3.org/2000/svg")
def flatten_viewports(node):
    # Qt SVG does not render these nested viewports like librsvg. Convert their
    # preserveAspectRatio=meet layout to equivalent vector transforms.
    for child in list(node):
        flatten_viewports(child)
        if child.tag.rsplit("}", 1)[-1] != "svg":
            continue
        vx, vy, vw, vh = map(float, child.get("viewBox").split())
        x, y = float(child.get("x", 0)), float(child.get("y", 0))
        width, height = float(child.get("width")), float(child.get("height"))
        scale = min(width / vw, height / vh)
        tx, ty = x + (width - vw * scale) / 2, y + (height - vh * scale) / 2
        child.tag = "{http://www.w3.org/2000/svg}g"
        child.attrib.clear()
        child.set("transform", f"translate({tx} {ty}) scale({scale}) translate({-vx} {-vy})")

templates = {}
for p in sorted((root / "assets/approved").glob("*.svg")):
    svg = ET.parse(p).getroot()
    flatten_viewports(svg)
    templates[p.stem] = ET.tostring(svg, encoding="unicode")
source = ".pragma library\n// Generated by scripts/build-icons.py; edit assets/approved/*.svg.\n"
source += "var templates = " + json.dumps(templates, ensure_ascii=False) + ";\n"
source += """
function rgb(c) { return "rgb(" + [c.r,c.g,c.b].map(v => Math.round(v*255)).join(",") + ")"; }
function url(name, tint, fill, filled) {
    var svg = templates[name];
    if (!svg) return "";
    svg = svg.replace(/currentColor/g, rgb(tint));
    if (filled && name.indexOf("bud-") === 0)
        svg = svg.replace('fill="none"', 'fill="' + rgb(fill) + '" fill-opacity="' + fill.a + '"');
    return "data:image/svg+xml," + encodeURIComponent(svg);
}
"""
(root / "interface/ApprovedIcons.js").write_text(source)
